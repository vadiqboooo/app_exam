def export(groups):
    book = Workbook()
    sheet = book.active
    # Same column arrangement as the real export, without personal data.
    sheet.append(["ФИО", "Статус обучения", None, "Активные группы", "Класс обучения "])
    sheet.append(["Иванов Иван", "Активен", None, groups, 11])
    sheet.append([None] * 5)
    output = BytesIO()
    book.save(output)
    book.close()
    output.seek(0)
    return output


def test_read_real_export_layout_and_multiple_memberships():
    groups = "Физика ПН 15:00,Биология ЕГЭ ПН, СБ 15:00 Рымарева Екатерина,Физика ПН 15:00"
    records = read_excel(export(groups))
    assert len(records) == 1
    assert records[0].full_name == "Иванов Иван"
    assert records[0].grade == 11
    assert records[0].is_active
    assert records[0].groups == ("Биология ЕГЭ ПН-СБ 15:00 Рымарева Екатерина", "Физика ПН 15:00")


def test_explicit_separator_can_preserve_commas_in_other_names():
    records = read_excel(export("Курс, часть 1|Физика"), ExcelFormat(group_separator=r"\|"))
    assert records[0].groups == ("Курс, часть 1", "Физика")
