def upgrade():
    with op.batch_alter_table("subjects") as batch_op:
        batch_op.add_column(sa.Column("primary_to_secondary_scale", sa.JSON(), nullable=True))
        batch_op.add_column(sa.Column("grade_scale", sa.JSON(), nullable=True))

    connection = op.get_bind()
    subjects = sa.table(
        "subjects",
        sa.column("name", sa.String),
        sa.column("format", sa.String),
        sa.column("primary_to_secondary_scale", sa.JSON),
        sa.column("grade_scale", sa.JSON),
    )
    for name, scale in EGE_SCALES.items():
        connection.execute(
            subjects.update()
            .where(subjects.c.name == name, subjects.c.format == "ege")
            .values(primary_to_secondary_scale=scale)
        )
    for name, ranges in OGE_SCALES.items():
        grade_scale = [
            {"grade": grade, "min": minimum, "max": maximum} for grade, minimum, maximum in ranges
        ]
        connection.execute(
            subjects.update()
            .where(subjects.c.name == name, subjects.c.format == "oge")
            .values(grade_scale=grade_scale)
        )


def downgrade():
    with op.batch_alter_table("subjects") as batch_op:
        batch_op.drop_column("grade_scale")
